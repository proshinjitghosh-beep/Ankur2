export type PhenologyTrack = 'annual' | 'perennial_mango' | 'vegetables';

export interface DimensionThresholds {
  heat: {
    tempMaxStartC: number;
    tempMaxModerateC: number;
    tempMaxHighC: number;
    tempMaxCriticalC: number;
    hourlyWarmThresholdC: number;
    minNightStressC: number;
    provenance: ThresholdProvenance;
  };
  rainfall: {
    rain24hModerateMm: number;
    rain24hHighMm: number;
    rain24hCriticalMm: number;
    rain72hModerateMm: number;
    rain72hHighMm: number;
    rain72hCriticalMm: number;
    drainageSensitivityNote: string;
    provenance: ThresholdProvenance;
  };
  drought: {
    deficitModerateMm: number;
    deficitHighMm: number;
    deficitCriticalMm: number;
    soilDryM3PerM3: number;
    soilCriticalM3PerM3: number;
    provenance: ThresholdProvenance;
  };
  disease: {
    targetDiseases: string[];
    tempMinC: number;
    tempMaxC: number;
    rhProxyThresholdPct: number;
    wetHoursModerate: number;
    wetHoursHigh: number;
    wetHoursCritical: number;
    provenance: ThresholdProvenance;
  };
  wind: {
    gustModerateKmh: number;
    gustHighKmh: number;
    gustCriticalKmh: number;
    sustainedHighKmh: number;
    provenance: ThresholdProvenance;
  };
}

export interface CropGrowthStageSpec {
  id: string;
  label: string;
  minDay: number | null; // null for perennial Mango phenological stages
  maxDay: number | null;
  weights: Record<RiskDimensionId, number>; // Must sum strictly to 1.0
  thresholds: DimensionThresholds;
}

export interface CropVarietySpec {
  id: string;
  label: string;
  typicalCycleDays: number | null;
  expectedPlantingLabel: string;
  /** Month windows (1..12) when sowing/transplanting typically occurs in Bangladesh */
  plantingMonths: number[];
  /** Optional thermal tolerance modifier (°C offset applied to reproductive heat thresholds) */
  heatToleranceOffsetC?: number;
}

export interface VegetableSubtypeSpec {
  id: VegetableSubtype;
  label: string;
  examples: string;
  heatOffsetC: number;
  rainOffsetMm: number;
  diseaseRhOffsetPct: number;
}

export interface CropRiskProfileSpec {
  id: RiskCropId;
  name: string;
  localName: string;
  phenologyTrack: PhenologyTrack;
  typicalCycleDays: number | null;
  optimalTempRangeC: string;
  defaultPlantingWindowLabel: string;
  defaultPlantingMonths: number[];
  varieties: CropVarietySpec[];
  vegetableSubtypes?: VegetableSubtypeSpec[];
  unspecifiedStageWeights: Record<RiskDimensionId, number>;
  unspecifiedThresholds: DimensionThresholds;
  growthStages: CropGrowthStageSpec[];
}

